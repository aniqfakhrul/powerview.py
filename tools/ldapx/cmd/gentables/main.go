const header = "# Code generated by tools/ldapx/cmd/gentables from github.com/Macmod/ldapx@%s. DO NOT EDIT.\n\n"

var tokenFormatNames = []string{
	"UNDEFINED", "NA", "STRING", "OID", "BITWISE", "BOOLEAN", "DATE_TIME", "INT_TIME_INTERVAL",
	"DN_WITH_BINARY", "DN_STRING", "SID", "INT_ENUMERATION", "HEX_OBJECT_REPLICA_LINK",
	"STRING_OBJECT_IDENTIFIER", "STRING_UNICODE", "STRING_IA5", "STRING_NT_SECURITY_DESCRIPTOR",
	"STRING_TELETEX", "STRING_NUMERIC", "STRING_OBJECT_ACCESS_POINT", "STRING_OBJECT_PRESENTATION_ADDRESS",
}

func main() {
	repo := flag.String("repo", "../..", "powerview.py repository root")
	flag.Parse()

	module := moduleDir("github.com/Macmod/ldapx")
	revision := moduleVersion("github.com/Macmod/ldapx")
	head := fmt.Sprintf(header, revision)

	write(filepath.Join(*repo, "powerview/lib/ldapx/parser/_schema.py"), head+schema())
	write(filepath.Join(*repo, "powerview/lib/ldapx/middlewares/helpers/_tables.py"), head+unicodeTables())
	write(filepath.Join(*repo, "powerview/lib/ldapx/middlewares/filter/_object_categories.py"), head+objectCategories(module))
	write(filepath.Join(*repo, "powerview/lib/ldapx/_casing.py"), head+casing())
	write(filepath.Join(*repo, "powerview/lib/ldapx/_revision.py"), head+fmt.Sprintf("UPSTREAM_REVISION = %s\n", pyStr(revision)))
	write(filepath.Join(*repo, "tools/ldapx/fixtures/gorand_cooked.txt"), rngCooked())
}

func moduleDir(path string) string {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", path).Output()
	if err != nil {
		log.Fatalf("locating %s: %v", path, err)
	}
	return strings.TrimSpace(string(out))
}

func moduleVersion(path string) string {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Version}}", path).Output()
	if err != nil {
		log.Fatalf("resolving %s version: %v", path, err)
	}
	return strings.TrimSpace(string(out))
}

func write(path string, content string) {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s", path)
}

func pyStr(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r >= 0x20 && r < 0x7f:
			b.WriteRune(r)
		case r < 0x100:
			fmt.Fprintf(&b, "\\x%02x", r)
		case r < 0x10000:
			fmt.Fprintf(&b, "\\u%04x", r)
		default:
			fmt.Fprintf(&b, "\\U%08x", r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func pyStrList(items []string) string {
	quoted := make([]string, len(items))
	for i, item := range items {
		quoted[i] = "\t" + pyStr(item) + ",\n"
	}
	return "(\n" + strings.Join(quoted, "") + ")"
}

func schema() string {
	var b strings.Builder
	b.WriteString("from enum import IntEnum\n\n\nclass TokenFormat(IntEnum):\n")
	for i, name := range tokenFormatNames {
		fmt.Fprintf(&b, "\t%s = %d\n", name, i)
	}

	b.WriteString("\n\nNUMBER_FORMATS = frozenset((\n")
	for _, f := range ldapxparser.NumberFormats {
		fmt.Fprintf(&b, "\tTokenFormat.%s,\n", tokenFormatNames[f])
	}
	b.WriteString("))\n\nOIDS_MAP = {\n")
	for _, k := range sortedKeys(ldapxparser.OidsMap) {
		fmt.Fprintf(&b, "\t%s: %s,\n", pyStr(k), pyStr(ldapxparser.OidsMap[k]))
	}
	b.WriteString("}\n\nATTR_FORMATS = {\n")
	for _, k := range sortedKeys(ldapxparser.AttrContexts) {
		fmt.Fprintf(&b, "\t%s: TokenFormat.%s,\n", pyStr(k), tokenFormatNames[ldapxparser.AttrContexts[k].Format])
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "BITWISE_ATTRS = %s\n\n", pyStrList(ldapxparser.BitwiseAttrs))
	fmt.Fprintf(&b, "ROOTDSE_OPERATIONAL_ATTRS = %s\n\n", pyStrList(ldapxparser.RootDSEOperationalAttrs))
	fmt.Fprintf(&b, "RFC_OPERATIONAL_ATTRS = %s\n", pyStrList(ldapxparser.RFCOperationalAttrs))
	return b.String()
}

func runeRanges(runes []rune) [][2]rune {
	var ranges [][2]rune
	for _, r := range runes {
		if n := len(ranges); n > 0 && ranges[n-1][1] == r-1 {
			ranges[n-1][1] = r
			continue
		}
		ranges = append(ranges, [2]rune{r, r})
	}
	return ranges
}

func pyRanges(name string, runes []rune) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s = _expand((\n", name)
	for _, r := range runeRanges(runes) {
		fmt.Fprintf(&b, "\t(0x%04X, 0x%04X),\n", r[0], r[1])
	}
	b.WriteString("))\n\n")
	return b.String()
}

func caseTable(name string, mapping func(rune) rune) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s = _pairs(\n", name)
	line := ""
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		if m := mapping(r); m != r {
			line += pyStr(string(r) + string(m))[1:]
			line = line[:len(line)-1]
			if len(line) > 100 {
				fmt.Fprintf(&b, "\t\"%s\"\n", line)
				line = ""
			}
		}
	}
	if line != "" {
		fmt.Fprintf(&b, "\t\"%s\"\n", line)
	}
	b.WriteString(")\n\n")
	return b.String()
}

func unicodeTables() string {
	var b strings.Builder
	b.WriteString(`
def _expand(ranges):
	return "".join(chr(c) for low, high in ranges for c in range(low, high + 1))


`)
	b.WriteString(pyRanges("IGNORABLE_RUNES", helpers.IgnorableRunes))
	b.WriteString(pyRanges("COMBINING_RUNES", helpers.CombiningRunes))
	b.WriteString(pyRanges("MODIFIER_LETTER_RUNES", helpers.ModifierLetterRunes))
	b.WriteString(pyRanges("MODIFIER_SYMBOL_RUNES", helpers.ModifierSymbolRunes))
	b.WriteString(pyRanges("SYMBOL_RUNES", helpers.SymbolRunes))
	b.WriteString(pyRanges("PUNCTUATION_RUNES", helpers.PunctuationRunes))
	fmt.Fprintf(&b, "ALT_SPACE_RUNES = %s\n\n", pyStr(string(helpers.AltSpaceRunes)))
	fmt.Fprintf(&b, "VISIBLE_ALT_SPACE_RUNES = %s\n\n", pyStr(string(helpers.VisibleAltSpaceRunes)))

	keys := make([]rune, 0, len(helpers.SortKeyFoldMap))
	for k := range helpers.SortKeyFoldMap {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	b.WriteString("SORT_KEY_FOLD_MAP = {\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%s: %s,\n", pyStr(string(k)), pyStr(string(helpers.SortKeyFoldMap[k])))
	}
	b.WriteString("}\n\nFOLD_LIGATURES = (\n")
	for _, lg := range helpers.FoldLigatures {
		fmt.Fprintf(&b, "\t(%s, %s),\n", pyStr(lg.ASCII), pyStr(string(lg.R)))
	}
	b.WriteString(")\n\nFOLD_CLASS_MEMBERS = {\n")
	for _, k := range sortedKeys(helpers.FoldClassMembers) {
		fmt.Fprintf(&b, "\t%s: %s,\n", pyStr(k), pyStr(string(helpers.FoldClassMembers[k])))
	}
	b.WriteString("}\n")
	return b.String()
}

func casing() string {
	var b strings.Builder
	b.WriteString("\ndef _pairs(*chunks):\n\ttext = \"\".join(chunks)\n\treturn dict(zip(text[0::2], text[1::2]))\n\n\n")
	fmt.Fprintf(&b, "UNICODE_VERSION = %s\n\n", pyStr(unicode.Version))
	b.WriteString(caseTable("SIMPLE_UPPER", unicode.ToUpper))
	b.WriteString(caseTable("SIMPLE_LOWER", unicode.ToLower))
	b.WriteString(strings.TrimRight(caseTable("FOLD_CANONICAL", foldCanonical), "\n") + "\n")
	return b.String()
}

func foldCanonical(r rune) rune {
	canonical := r
	for next := unicode.SimpleFold(r); next != r; next = unicode.SimpleFold(next) {
		canonical = min(canonical, next)
	}
	return canonical
}

func objectCategories(module string) string {
	file := filepath.Join(module, "middlewares/filter/obfuscation.go")
	parsed, err := parser.ParseFile(token.NewFileSet(), file, nil, 0)
	if err != nil {
		log.Fatal(err)
	}
	entries := map[string]string{}
	ast.Inspect(parsed, func(n ast.Node) bool {
		spec, ok := n.(*ast.ValueSpec)
		if !ok || len(spec.Names) != 1 || spec.Names[0].Name != "objectCategoryClasses" {
			return true
		}
		for _, elt := range spec.Values[0].(*ast.CompositeLit).Elts {
			kv := elt.(*ast.KeyValueExpr)
			key, _ := strconv.Unquote(kv.Key.(*ast.BasicLit).Value)
			value, _ := strconv.Unquote(kv.Value.(*ast.BasicLit).Value)
			entries[key] = value
		}
		return false
	})
	if len(entries) == 0 {
		log.Fatal("objectCategoryClasses not found")
	}
	var b strings.Builder
	b.WriteString("OBJECT_CATEGORY_CLASSES = {\n")
	for _, k := range sortedKeys(entries) {
		fmt.Fprintf(&b, "\t%s: %s,\n", pyStr(k), pyStr(entries[k]))
	}
	b.WriteString("}\n")
	return b.String()
}

func rngCooked() string {
	file := filepath.Join(runtime.GOROOT(), "src/math/rand/rng.go")
	parsed, err := parser.ParseFile(token.NewFileSet(), file, nil, 0)
	if err != nil {
		log.Fatal(err)
	}
	var values []string
	ast.Inspect(parsed, func(n ast.Node) bool {
		spec, ok := n.(*ast.ValueSpec)
		if !ok || len(spec.Names) != 1 || spec.Names[0].Name != "rngCooked" {
			return true
		}
		for _, elt := range spec.Values[0].(*ast.CompositeLit).Elts {
			switch v := elt.(type) {
			case *ast.BasicLit:
				values = append(values, v.Value)
			case *ast.UnaryExpr:
				values = append(values, v.Op.String()+v.X.(*ast.BasicLit).Value)
			}
		}
		return false
	})
	if len(values) != 607 {
		log.Fatalf("unexpected rngCooked length %d", len(values))
	}
	return strings.Join(values, "\n") + "\n"
}
